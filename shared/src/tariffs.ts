export function tariffFor(city: string, body: BodyType): number {
  const r = TARIFF.find((t) => t[0] === city);
  return r ? r[BODY[body].i] : 0;
}

export function routeFor(city: string): string[] {
  const out: string[] = [];
  let c: string | null = city;
  while (c && NET[c]) {
    out.unshift(c);
    c = NET[c][0];
  }
  return out;
}

export function kmTo(city: string): number {
  return NET[city]?.[1] ?? 0;
}
