export type Body = "sedan" | "cross" | "van";
export const BODY: Record<Body, { i: 1 | 2 | 3; name: string }> = {
  sedan: { i: 1, name: "Седан / хэтчбек" },
  cross: { i: 2, name: "Кроссовер" },
  van: { i: 3, name: "Минивен / джип" },
};
export const INS_RATE = 0.003;   // страховка 0,3% от оценочной стоимости
export const SV_SHARE = 0.4;     // доля страховой компании

export function tariffFor(city: string, body: Body): number | null {
  const r = TARIFF.find((t) => t[0] === city);
  return r ? r[BODY[body].i] : null;
}

// кэшбэк партнёра прибавляется к стоимости перевозки, но в договоре отдельно не показывается
export function quote(city: string, body: Body, value: number, cashback = 0) {
  const tariff = tariffFor(city, body);
  if (tariff == null) return null;
  const delivery = tariff + cashback, insurance = Math.round(value * INS_RATE);
  return { tariff, cashback, delivery, insurance, total: delivery + insurance, needsManager: body === "van" };
}
