export const TRANSFER_CITY = "Новосибирск";
export const ORIGIN_CITY = "Владивосток";

export function routeFor(city: string): string[] {
  const out: string[] = [];
  let c: string | null = city;
  while (c && NET[c]) { out.unshift(c); c = NET[c][0]; }
  return out;
}
export const kmOf = (city: string | null | undefined) => (city && NET[city] ? NET[city][1] : 0);

// машина может ехать через терминал, если он на её маршруте и это не конечный город
export const canTransfer = (city: string) => city !== TRANSFER_CITY && routeFor(city).includes(TRANSFER_CITY);
